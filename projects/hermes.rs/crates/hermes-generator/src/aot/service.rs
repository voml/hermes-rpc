//! `service.ts`、`routes.ts` 与 `metadata.ts` 渲染。
//!
//! 三个文件都只导出常量、类型和纯函数：没有 runtime 依赖，也没有宿主协议选择。
//! identity、fingerprint 与 canonical path 全部来自上游 artifact，渲染层不推导。

use vos_types::ContractArtifact;

use crate::{
    aot::{AotTarget, Bindings},
    naming::string_literal,
    plan::{FileOwnership, GeneratedFile},
};

/// service / method identity 常量模块。
pub(crate) const SERVICE_PATH: &str = "hermes/service.ts";
/// `(serviceId, methodName) -> methodId` 路由表模块。
pub(crate) const ROUTES_PATH: &str = "hermes/routes.ts";
/// 生成 revision 与来源元数据模块。
pub(crate) const METADATA_PATH: &str = "hermes/metadata.ts";

const HEADER: &str = "// Generated by `hermes-generator` from a `vos/hermes.contract/v0` artifact. Do not edit by hand.\n";

const CONTRACT_FORMAT: &str = "vos/hermes.contract/v0";

/// 渲染 service 模块。
pub(crate) fn render_service(bindings: &Bindings) -> GeneratedFile {
    let mut out = String::new();
    out.push_str(HEADER);
    out.push('\n');
    out.push_str(&format!("export const contractVersion = {};\n\n", string_literal(CONTRACT_FORMAT)));

    out.push_str("export const serviceIds = {\n");
    for service in &bindings.services {
        out.push_str(&format!("  {}: {},\n", service.key, string_literal(&service.service_id)));
    }
    out.push_str("} as const;\n\n");

    out.push_str("export const serviceNames = {\n");
    for service in &bindings.services {
        out.push_str(&format!("  {}: {},\n", service.key, string_literal(&service.raw_name)));
    }
    out.push_str("} as const;\n\n");

    out.push_str("export const serviceIdsByName: Readonly<Record<string, string>> = {\n");
    for service in &bindings.services {
        out.push_str(&format!("  {}: {},\n", string_literal(&service.raw_name), string_literal(&service.service_id)));
    }
    out.push_str("};\n\n");

    out.push_str("export const methodIds = {\n");
    for service in &bindings.services {
        out.push_str(&format!("  {}: {{\n", service.key));
        for method in &service.methods {
            out.push_str(&format!("    {}: {},\n", method.ts_name, string_literal(&method.method_id)));
        }
        out.push_str("  },\n");
    }
    out.push_str("} as const;\n\n");

    out.push_str("export const serviceFingerprints = {\n");
    for service in &bindings.services {
        out.push_str(&format!("  {}: {},\n", service.key, string_literal(&service.fingerprint)));
    }
    out.push_str("} as const;\n\n");

    out.push_str("export const methodFingerprints = {\n");
    for service in &bindings.services {
        out.push_str(&format!("  {}: {{\n", service.key));
        for method in &service.methods {
            out.push_str(&format!("    {}: {},\n", method.ts_name, string_literal(&method.fingerprint)));
        }
        out.push_str("  },\n");
    }
    out.push_str("} as const;\n\n");

    out.push_str(
        "export type ServiceKey = keyof typeof serviceIds;\n\
         export type ServiceId = (typeof serviceIds)[ServiceKey];\n\
         export type MethodKey<S extends ServiceKey> = keyof (typeof methodIds)[S];\n\
         export type MethodId = { [S in ServiceKey]: (typeof methodIds)[S][MethodKey<S>] }[ServiceKey];\n",
    );

    if !bindings.user_types.is_empty() {
        out.push_str(
            "\n// The artifact carries durable user type identities but not field shapes.\n\
             // Each alias is nominal: the target project owns the structural shape.\n",
        );
        for user_type in &bindings.user_types {
            out.push_str(&format!("// canonical path: {}\n", user_type.path));
            out.push_str(&format!("export type {} = {{ readonly __vosTypeId: {} }};\n", user_type.name, user_type.type_id));
        }
    }

    GeneratedFile::new(SERVICE_PATH, out, FileOwnership::Generated)
}

/// 渲染路由表模块。
pub(crate) fn render_routes(bindings: &Bindings) -> GeneratedFile {
    let mut out = String::new();
    out.push_str(HEADER);
    out.push('\n');
    out.push_str("import { serviceIdsByName } from \"./service\";\n\n");

    out.push_str(
        "export interface ServiceRoute {\n\
         \x20 readonly serviceId: string;\n\
         \x20 readonly serviceName: string;\n\
         \x20 readonly methodName: string;\n\
         \x20 readonly methodId: string;\n\
         \x20 readonly operationId: string;\n\
         \x20 readonly stream: \"unary\" | \"server-stream\";\n\
         }\n\n",
    );

    out.push_str("const routeTable = {\n");
    for service in &bindings.services {
        for method in &service.methods {
            out.push_str(&format!("  {}: {{\n", string_literal(&method.route_key)));
            out.push_str(&format!("    serviceId: {},\n", string_literal(&service.service_id)));
            out.push_str(&format!("    serviceName: {},\n", string_literal(&service.raw_name)));
            out.push_str(&format!("    methodName: {},\n", string_literal(&method.raw_name)));
            out.push_str(&format!("    methodId: {},\n", string_literal(&method.method_id)));
            out.push_str(&format!("    operationId: {},\n", string_literal(&method.operation_id)));
            out.push_str(&format!("    stream: {},\n", string_literal(super::stream_name(method.stream))));
            out.push_str("  },\n");
        }
    }
    out.push_str("} as const;\n\n");

    out.push_str(
        "export const routes: Readonly<Record<string, ServiceRoute>> = routeTable;\n\
         export type RouteKey = keyof typeof routeTable;\n\n\
         export function resolveRoute(serviceName: string, methodName: string): ServiceRoute | undefined {\n\
         \x20 const serviceId = serviceIdsByName[serviceName];\n\
         \x20 if (serviceId === undefined) {\n\
         \x20   return undefined;\n\
         \x20 }\n\
         \x20 return routes[`${serviceId}/${methodName}`];\n\
         }\n\n\
         export function requireRoute(serviceName: string, methodName: string): ServiceRoute {\n\
         \x20 const route = resolveRoute(serviceName, methodName);\n\
         \x20 if (route === undefined) {\n\
         \x20   throw new Error(`unknown service method: ${serviceName}.${methodName}`);\n\
         \x20 }\n\
         \x20 return route;\n\
         }\n\n\
         export function methodIdOf(serviceId: string, methodName: string): string | undefined {\n\
         \x20 return routes[`${serviceId}/${methodName}`]?.methodId;\n\
         }\n",
    );

    GeneratedFile::new(ROUTES_PATH, out, FileOwnership::Generated)
}

/// 渲染 metadata 模块。
pub(crate) fn render_metadata(bindings: &Bindings, artifact: &ContractArtifact, target: AotTarget) -> GeneratedFile {
    let mut out = String::new();
    out.push_str(HEADER);
    out.push('\n');
    out.push_str(&format!("export const contractVersion = {};\n", string_literal(CONTRACT_FORMAT)));
    out.push_str(&format!("export const contractFingerprint = {};\n", string_literal(&artifact.fingerprint)));
    out.push_str(&format!(
        "export const generatorRevision = {};\n",
        string_literal(concat!("hermes-generator@", env!("CARGO_PKG_VERSION")))
    ));
    out.push_str(&format!("export const aotTarget = {} as const;\n\n", string_literal(target.as_str())));

    out.push_str("/** Source provenance carried by the contract artifact. */\nexport const provenance = {\n");
    out.push_str(&format!("  producerName: {},\n", string_literal(&artifact.producer.name)));
    out.push_str(&format!("  producerVersion: {},\n", string_literal(&artifact.producer.version)));
    out.push_str("} as const;\n\n");

    out.push_str("export const serviceMetadata = {\n");
    for service in &bindings.services {
        out.push_str(&format!("  {}: {{\n", service.key));
        out.push_str(&format!("    serviceId: {},\n", string_literal(&service.service_id)));
        out.push_str(&format!("    serviceName: {},\n", string_literal(&service.raw_name)));
        let path = service.canonical_path.iter().map(|segment| string_literal(segment)).collect::<Vec<_>>().join(", ");
        out.push_str(&format!("    canonicalPath: [{path}],\n"));
        out.push_str(&format!("    fingerprint: {},\n", string_literal(&service.fingerprint)));
        out.push_str("    methods: {\n");
        for method in &service.methods {
            out.push_str(&format!("      {}: {{\n", method.ts_name));
            out.push_str(&format!("        methodId: {},\n", string_literal(&method.method_id)));
            out.push_str(&format!("        methodName: {},\n", string_literal(&method.raw_name)));
            out.push_str(&format!("        operationId: {},\n", string_literal(&method.operation_id)));
            out.push_str(&format!("        stream: {},\n", string_literal(super::stream_name(method.stream))));
            out.push_str(&format!("        fingerprint: {},\n", string_literal(&method.fingerprint)));
            out.push_str("      },\n");
        }
        out.push_str("    },\n");
        out.push_str("  },\n");
    }
    out.push_str("} as const;\n");

    GeneratedFile::new(METADATA_PATH, out, FileOwnership::Generated)
}
