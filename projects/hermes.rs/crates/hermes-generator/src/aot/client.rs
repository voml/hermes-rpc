//! `client.ts` 渲染。
//!
//! client 是普通 AOT 源码：不 import 任何 Hermes npm 包或 runtime，只声明
//! transport-neutral 的 dispatch 注入点。desktop 与 web 的差异只有 server-stream
//! 的返回值形状，文件之间不互相 import 宿主实现。

use crate::{
    aot::{AotTarget, Bindings, dispatch_name, stream_result},
    plan::{FileOwnership, GeneratedFile},
};

/// client 模块路径。
pub(crate) const CLIENT_PATH: &str = "hermes/client.ts";

/// 渲染 client 模块。
pub(crate) fn render(bindings: &Bindings, target: AotTarget) -> GeneratedFile {
    let mut out = String::new();
    out.push_str("// Generated by `hermes-generator` from a `vos/hermes.contract/v0` artifact. Do not edit by hand.\n");
    out.push_str(&format!("// AOT target: {}.\n\n", target.as_str()));

    if !bindings.user_types.is_empty() {
        let user_types = bindings.user_types.iter().map(|user_type| user_type.name.as_str()).collect::<Vec<_>>();
        out.push_str(&format!("import type {{ {} }} from \"./service\";\n", user_types.join(", ")));
    }
    out.push_str("import { methodIds, serviceIds } from \"./service\";\n\n");

    out.push_str(
        "export interface CallOptions {\n\
         \x20 readonly deadline?: number;\n\
         \x20 readonly signal?: AbortSignal;\n\
         \x20 readonly metadata?: Readonly<Record<string, string>>;\n\
         }\n\n",
    );

    out.push_str(
        "export interface HermesCall {\n\
         \x20 readonly serviceId: string;\n\
         \x20 readonly methodId: string;\n\
         \x20 readonly request: unknown;\n\
         \x20 readonly options: CallOptions | undefined;\n\
         }\n\n",
    );

    out.push_str(&format!(
        "export interface HermesDispatch {{\n\
         \x20 unary(call: HermesCall): Promise<unknown>;\n\
         \x20 serverStream(call: HermesCall): {}<unknown>;\n\
         }}\n\n",
        target.stream_type()
    ));

    for service in &bindings.services {
        out.push_str(&format!("export class {} {{\n", service.class_name));
        out.push_str(&format!("  readonly serviceId = serviceIds.{};\n\n", service.key));
        out.push_str("  constructor(private readonly dispatch: HermesDispatch) {}\n");

        for method in &service.methods {
            let result = stream_result(target, method.stream, &method.response);
            out.push_str(&format!(
                "\n  {}(request: {}, options?: CallOptions): {} {{\n",
                method.ts_name, method.request, result
            ));
            out.push_str(&format!("    return this.dispatch.{}({{\n", dispatch_name(method.stream)));
            out.push_str("      serviceId: this.serviceId,\n");
            out.push_str(&format!("      methodId: methodIds.{}.{},\n", service.key, method.ts_name));
            out.push_str("      request,\n");
            out.push_str("      options,\n");
            out.push_str(&format!("    }}) as {};\n", result));
            out.push_str("  }\n");
        }

        out.push_str("}\n\n");
    }

    out.push_str("export function createServiceClients(dispatch: HermesDispatch) {\n  return {\n");
    for service in &bindings.services {
        out.push_str(&format!("    {}: new {}(dispatch),\n", service.key, service.class_name));
    }
    out.push_str("  };\n}\n");

    GeneratedFile::new(CLIENT_PATH, out, FileOwnership::Generated)
}
