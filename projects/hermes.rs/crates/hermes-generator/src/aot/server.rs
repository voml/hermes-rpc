//! `hermes/service/server.ts` 与一次性 `hermes/service/handlers.ts` 渲染。
//!
//! server 侧只把 method identity 绑定到用户 handler，不复制 dispatcher，也不
//! import 任何 runtime。`bindService` 通过 `requireRoute` 拒绝未知 method，并保留
//! operation binding 供宿主做运行期校验。

use crate::{
    aot::{AotTarget, Bindings, handler_result, output_path},
    naming::string_literal,
    plan::{FileOwnership, GeneratedFile},
};

/// 渲染 server 绑定模块。
pub(crate) fn render(bindings: &Bindings, target: AotTarget) -> GeneratedFile {
    let mut out = String::new();
    out.push_str("// Generated by `hermes-generator` from a `vos/hermes.contract/v0` artifact. Do not edit by hand.\n");
    out.push_str(&format!("// AOT target: {}.\n\n", target.as_str()));

    if !bindings.user_types.is_empty() {
        let user_types = bindings.user_types.iter().map(|user_type| user_type.name.as_str()).collect::<Vec<_>>();
        out.push_str(&format!("import type {{ {} }} from \"./service\";\n", user_types.join(", ")));
    }
    out.push_str("import { requireRoute } from \"./routes\";\n");
    out.push_str("import type { ServiceRoute } from \"./routes\";\n\n");

    out.push_str(
        "export interface ServiceContext {\n\
         \x20 readonly serviceId: string;\n\
         \x20 readonly methodId: string;\n\
         \x20 readonly operationId: string;\n\
         \x20 readonly deadline?: number;\n\
         \x20 readonly signal?: AbortSignal;\n\
         \x20 readonly metadata: Readonly<Record<string, string>>;\n\
         }\n\n",
    );

    for service in &bindings.services {
        out.push_str(&format!("export interface {}Handlers {{\n", service.class_name.trim_end_matches("Client")));
        for method in &service.methods {
            out.push_str(&format!(
                "  {}(context: ServiceContext, request: {}): {};\n",
                method.ts_name,
                method.request,
                handler_result(target, method.stream, &method.response)
            ));
        }
        out.push_str("}\n\n");
    }

    out.push_str("export interface ServiceHandlers {\n");
    for service in &bindings.services {
        out.push_str(&format!("  {}: {}Handlers;\n", service.key, service.class_name.trim_end_matches("Client")));
    }
    out.push_str("}\n\n");

    out.push_str(
        "export interface MethodBinding {\n\
         \x20 readonly route: ServiceRoute;\n\
         \x20 readonly handler: (context: ServiceContext, request: unknown) => unknown;\n\
         }\n\n",
    );

    out.push_str(
        "export function bindService(handlers: ServiceHandlers): MethodBinding[] {\n\
         \x20 return [\n",
    );
    for service in &bindings.services {
        for method in &service.methods {
            out.push_str("    {\n");
            out.push_str(&format!(
                "      route: requireRoute({}, {}),\n",
                string_literal(&service.raw_name),
                string_literal(&method.raw_name)
            ));
            out.push_str(&format!(
                "      handler: (context, request) => handlers.{}.{}(context, request as {}),\n",
                service.key, method.ts_name, method.request
            ));
            out.push_str("    },\n");
        }
    }
    out.push_str("  ];\n}\n\n");

    out.push_str(
        "export function assertOperationBindings(\n\
         \x20 bindings: readonly MethodBinding[],\n\
         \x20 operations: ReadonlySet<string>,\n\
         ): void {\n\
         \x20 const missing = bindings\n\
         \x20   .filter((binding) => !operations.has(binding.route.operationId))\n\
         \x20   .map((binding) => `${binding.route.serviceName}.${binding.route.methodName}`);\n\
         \x20 if (missing.length > 0) {\n\
         \x20   throw new Error(`methods without an operation binding: ${missing.join(\", \")}`);\n\
         \x20 }\n\
         }\n",
    );

    GeneratedFile::new(output_path("server.ts"), out, FileOwnership::Generated)
}

/// 渲染一次性业务模板。
pub(crate) fn render_template(bindings: &Bindings) -> GeneratedFile {
    let mut out = String::new();
    out.push_str("// Created once by `hermes-generator`. This file is never overwritten.\n");
    out.push_str("// Implement each service method here. Generated bindings route by method and operation id.\n\n");
    out.push_str("import type { ServiceHandlers } from \"./server\";\n\n");

    if bindings.services.is_empty() {
        out.push_str("export const handlers: ServiceHandlers = {};\n");
        return GeneratedFile::new(output_path("handlers.ts"), out, FileOwnership::Template);
    }

    out.push_str("export const handlers: ServiceHandlers = {\n");
    for service in &bindings.services {
        out.push_str(&format!("  {}: {{\n", service.key));
        for method in &service.methods {
            out.push_str(&format!(
                "    {}: () => {{\n      throw new Error({});\n    }},\n",
                method.ts_name,
                string_literal(&format!("method `{}.{}` is not implemented", service.raw_name, method.raw_name))
            ));
        }
        out.push_str("  },\n");
    }
    out.push_str("};\n");

    GeneratedFile::new(output_path("handlers.ts"), out, FileOwnership::Template)
}
